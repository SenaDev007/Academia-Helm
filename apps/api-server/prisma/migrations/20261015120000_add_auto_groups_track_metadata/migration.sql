-- ============================================================================
-- Migration: Auto-groups par piste FR/EN + metadata + DMs automatiques
-- ============================================================================
-- Extension du système d'auto-groups Helm Connect pour supporter :
--   1. Distinction FR/EN sur les canaux administration et pédagogique
--   2. Canal général (tous enseignants + administration) pour le conseil des classes
--   3. Canaux conseil de classe par piste (FR/EN) × niveau (maternelle/primaire/secondaire)
--   4. Métadonnées JSON sur chat_auto_groups et chat_conversations (pour tags UI)
--
-- Tables modifiées :
--   chat_auto_groups     — + academicTrackId TEXT + metadata JSONB
--   chat_conversations   — + academicTrackId TEXT + metadata JSONB
-- ============================================================================

-- ═════════════════════════════════════════════════════════════════
--  1. EXTENSION DE chat_auto_groups
--     academicTrackId : FK vers academic_tracks.id (NULL = les deux pistes)
--     metadata : JSONB pour tags UI (category, levelCode, trackCode, etc.)
-- ═════════════════════════════════════════════════════════════════
ALTER TABLE "chat_auto_groups" ADD COLUMN IF NOT EXISTS "academicTrackId" TEXT;
ALTER TABLE "chat_auto_groups" ADD COLUMN IF NOT EXISTS "metadata" JSONB;

-- Index pour la recherche par piste
CREATE INDEX IF NOT EXISTS "chat_auto_groups_tenant_year_track_idx"
  ON "chat_auto_groups" ("tenantId", "academicYearId", "academicTrackId");

-- Contrainte FK vers academic_tracks (optionnelle — NULL autorisé)
ALTER TABLE "chat_auto_groups"
  DROP CONSTRAINT IF EXISTS "chat_auto_groups_academicTrackId_fkey";
ALTER TABLE "chat_auto_groups"
  ADD CONSTRAINT "chat_auto_groups_academicTrackId_fkey"
    FOREIGN KEY ("academicTrackId") REFERENCES "academic_tracks"("id") ON DELETE SET NULL;

-- ═════════════════════════════════════════════════════════════════
--  2. EXTENSION DE chat_conversations
--     academicTrackId : piste FR/EN de la conversation (NULL = non applicable)
--     metadata : JSONB pour catégorie UI, levelCode, trackCode, autoGenerated, etc.
-- ═════════════════════════════════════════════════════════════════
ALTER TABLE "chat_conversations" ADD COLUMN IF NOT EXISTS "academicTrackId" TEXT;
ALTER TABLE "chat_conversations" ADD COLUMN IF NOT EXISTS "metadata" JSONB;

-- Index pour le filtrage par piste
CREATE INDEX IF NOT EXISTS "chat_conversations_tenant_track_idx"
  ON "chat_conversations" ("tenantId", "academicTrackId");

-- Contrainte FK vers academic_tracks
ALTER TABLE "chat_conversations"
  DROP CONSTRAINT IF EXISTS "chat_conversations_academicTrackId_fkey";
ALTER TABLE "chat_conversations"
  ADD CONSTRAINT "chat_conversations_academicTrackId_fkey"
    FOREIGN KEY ("academicTrackId") REFERENCES "academic_tracks"("id") ON DELETE SET NULL;

-- ═════════════════════════════════════════════════════════════════
--  3. MISE À JOUR DE L'UNICITÉ DES AUTO-GROUPS
--     L'unicité existante sur (tenantId, academicYearId, groupType, classId,
--     subjectId, roleType, levelId) doit être étendue pour inclure
--     academicTrackId — sinon deux canaux ADMIN_TRACK FR et EN auraient
--     le même hash et le second écraserait le premier.
-- ═════════════════════════════════════════════════════════════════
-- L'unicité est gérée en code par createOrUpdateAutoGroup avec COALESCE.
-- On ajoute un index supplémentaire pour accélérer la recherche par piste.
CREATE INDEX IF NOT EXISTS "chat_auto_groups_dedup_track_idx"
  ON "chat_auto_groups" ("tenantId", "academicYearId", "groupType", "academicTrackId")
  WHERE "classId" IS NULL AND "subjectId" IS NULL AND "levelId" IS NULL;
